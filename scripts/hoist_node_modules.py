#!/usr/bin/env python3
"""Rewrite a pnpm-style `node_modules` (a `.aspect_rules_js/` store plus
symlinks) into the flat, symlink-free layout npm produces.

Why: Tauri's resource bundler copies regular files only, and in the
store layout every package is reached through a link — dereferencing
them is not enough, because Node resolves a package's dependencies from
the directory it *really* lives in, and a copy no longer lives beside
its store siblings. The npm layout needs no links: a package's
dependencies are found by walking up from its own directory through
each enclosing `node_modules`.

    hoist_node_modules.py <node_modules dir>

The directory is replaced in place. A package that every dependent
agrees on is placed once at the top; where two dependents want
different versions (or different peer-dependency instances — pnpm keys
those apart too), the one that could not be hoisted is nested under
the dependent that needs it, exactly as npm would.
"""

from __future__ import annotations

import os
import shutil
import sys
from dataclasses import dataclass, field
from pathlib import Path

STORE = ".aspect_rules_js"


@dataclass
class StoreEntry:
    key: str
    name: str
    package_dir: Path
    deps: dict[str, str] = field(default_factory=dict)  # dep name -> store key


@dataclass
class Placed:
    key: str
    name: str
    parent: Placed | None
    children: dict[str, Placed] = field(default_factory=dict)

    def resolve(self, name: str) -> Placed | None:
        node: Placed | None = self
        while node is not None:
            if name in node.children:
                return node.children[name]
            node = node.parent
        return None


def package_names(node_modules: Path):
    """Every `<name>` or `@scope/<name>` entry directly under `node_modules`."""
    for entry in sorted(node_modules.iterdir()):
        if entry.name == STORE:
            continue
        if entry.name.startswith("@") and entry.is_dir() and not entry.is_symlink():
            for scoped in sorted(entry.iterdir()):
                yield f"{entry.name}/{scoped.name}", scoped
        else:
            yield entry.name, entry


def store_key_of(link: Path, store: Path) -> str:
    target = (link.parent / os.readlink(link)).resolve()
    try:
        rel = target.relative_to(store.resolve())
    except ValueError:
        sys.exit(f"hoist: {link} points outside the store: {target}")
    return rel.parts[0]


def read_store(root: Path) -> tuple[dict[str, StoreEntry], dict[str, str]]:
    store = root / STORE
    if not store.is_dir():
        sys.exit(f"hoist: {root} has no {STORE}/ — not a pnpm-style tree")
    entries: dict[str, StoreEntry] = {}
    for key_dir in sorted(store.iterdir()):
        modules = key_dir / "node_modules"
        if not modules.is_dir():
            continue
        entry: StoreEntry | None = None
        deps: dict[str, str] = {}
        for name, path in package_names(modules):
            if path.is_symlink():
                deps[name] = store_key_of(path, store)
            elif entry is None:
                entry = StoreEntry(key=key_dir.name, name=name, package_dir=path)
            else:
                sys.exit(
                    f"hoist: two real packages in {modules}: {entry.name} and {name}"
                )
        if entry is None:
            sys.exit(f"hoist: no real package in {modules}")
        entry.deps = deps
        entries[entry.key] = entry
    roots = {
        name: store_key_of(path, store)
        for name, path in package_names(root)
        if path.is_symlink()
    }
    if not roots:
        sys.exit(f"hoist: no top-level package links in {root}")
    return entries, roots


def plan(entries: dict[str, StoreEntry], roots: dict[str, str]) -> Placed:
    top = Placed(key="", name="", parent=None)
    queue: list[Placed] = []
    for name, key in sorted(roots.items()):
        node = Placed(key=key, name=name, parent=top)
        top.children[name] = node
        queue.append(node)
    while queue:
        node = queue.pop(0)
        entry = entries.get(node.key)
        if entry is None:
            sys.exit(
                f"hoist: {node.name} links to a store entry that is not there: {node.key}"
            )
        for dep_name, dep_key in sorted(entry.deps.items()):
            found = node.resolve(dep_name)
            if found is not None and found.key == dep_key:
                continue
            # Not reachable at that version: hoist to the top if the name
            # is free there, else nest it under the package that needs it.
            parent = top if dep_name not in top.children else node
            if dep_name in parent.children:
                sys.exit(
                    f"hoist: {node.name} needs {dep_name}@{dep_key}, but {parent.name} already nests {parent.children[dep_name].key}"
                )
            child = Placed(key=dep_key, name=dep_name, parent=parent)
            parent.children[dep_name] = child
            queue.append(child)
    return top


def check(top: Placed, entries: dict[str, StoreEntry]) -> None:
    """Every placed package finds each of its dependencies, at the key it
    wants, by the walk-up Node will do — a placement made later must not
    have shadowed one made earlier."""
    stack = list(top.children.values())
    while stack:
        node = stack.pop()
        for dep_name, dep_key in entries[node.key].deps.items():
            found = node.resolve(dep_name)
            if found is None or found.key != dep_key:
                sys.exit(
                    f"hoist: {node.name} ({node.key}) would resolve {dep_name} to "
                    f"{found.key if found else 'nothing'}, wants {dep_key}"
                )
        stack.extend(node.children.values())


def materialize(
    top: Placed, entries: dict[str, StoreEntry], dest: Path
) -> tuple[int, int]:
    placed = nested = 0
    stack = [(top, dest)]
    while stack:
        node, modules = stack.pop()
        for name, child in sorted(node.children.items()):
            target = modules / name
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copytree(entries[child.key].package_dir, target, symlinks=True)
            placed += 1
            if node is not top:
                nested += 1
            if child.children:
                stack.append((child, target / "node_modules"))
    return placed, nested


def main(argv: list[str]) -> None:
    if len(argv) != 2:
        sys.exit(__doc__)
    root = Path(argv[1])
    entries, roots = read_store(root)
    top = plan(entries, roots)
    check(top, entries)
    fresh = root.with_name(root.name + ".hoisted")
    shutil.rmtree(fresh, ignore_errors=True)
    fresh.mkdir()
    placed, nested = materialize(top, entries, fresh)
    links = [p for p in fresh.rglob("*") if p.is_symlink()]
    if links:
        sys.exit(
            f"hoist: a package carries symlinks of its own, which the bundler would drop: {links[0]}"
        )
    shutil.rmtree(root)
    fresh.rename(root)
    print(
        f">>> hoist: {root}: {placed} packages, {nested} nested for a version conflict",
        file=sys.stderr,
    )


if __name__ == "__main__":
    main(sys.argv)
